package ru.itmo.ddia.hw1.dashboards;

import com.grafana.foundation.dashboard.Dashboard;
import com.grafana.foundation.dashboard.DashboardBuilder;
import com.grafana.foundation.dashboard.DashboardDashboardTimeBuilder;
import com.grafana.foundation.dashboard.DataSourceRef;
import com.grafana.foundation.dashboard.QueryVariableBuilder;
import com.grafana.foundation.dashboard.RowBuilder;
import com.grafana.foundation.dashboard.StringOrMap;
import com.grafana.foundation.dashboard.VariableRefresh;
import com.grafana.foundation.dashboard.VariableSort;
import com.grafana.foundation.prometheus.DataqueryBuilder;
import com.grafana.foundation.timeseries.TimeseriesPanelBuilder;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.io.FileDescriptor;
import java.io.FileOutputStream;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

/**
 * CLI: builds a dashboard from the handler list reported by the running application
 * and uploads it to Grafana.
 *
 * Repeated runs are idempotent: the dashboard is addressed by a stable uid and sent with
 * overwrite, so docker compose up never produces duplicates.
 */
public final class DashboardGenerator {

    private static final Logger log = LoggerFactory.getLogger(DashboardGenerator.class);

    private static final String DASHBOARD_UID = "ddia-hw1-golden-signals";

    public static void main(String[] args) throws Exception {
        String datasourceUid = Env.orDefault("GRAFANA_DATASOURCE_UID", "victoriametrics");
        String serviceUrl = Env.required("TARGET_SERVICE_URL");
        boolean dryRun = Boolean.parseBoolean(Env.orDefault("DRY_RUN", "false"));

        MeasuredHandlers discovered = MeasuredHandlers.fetch(serviceUrl);
        log.info("Discovered {} handlers, deployment: {}",
                discovered.handlers().size(), discovered.deployment());

        Dashboard dashboard = buildDashboard(discovered, datasourceUid).build();

        if (dryRun) {
            PrintStream out = new PrintStream(new FileOutputStream(FileDescriptor.out), true, StandardCharsets.UTF_8);
            out.println(dashboard.toJSON());
            out.flush();
            return;
        }

        String grafanaUrl = Env.required("GRAFANA_URL");
        String token = Files.readString(Path.of(Env.required("GRAFANA_SA_TOKEN_FILE"))).trim();
        String payload = """
                {"dashboard": %s, "overwrite": true, "message": "generated by dashboard-generator"}
                """.formatted(dashboard.toJSON());

        GrafanaClient grafana = GrafanaClient.withToken(grafanaUrl, token);
        String body = grafana.post("/api/dashboards/db", payload)
                .requireOk("dashboard upload")
                .body();
        log.info("Dashboard uploaded: {}", body);
    }

    private static DashboardBuilder buildDashboard(MeasuredHandlers discovered, String datasourceUid) {
        DataSourceRef datasource = new DataSourceRef("prometheus", datasourceUid);
        String latency = discovered.latencyMetric();
        String throughput = discovered.throughputMetric();

        // the dashboard is not editable
        DashboardBuilder dashboard = new DashboardBuilder("DDIA HW1 — golden signals")
                .uid(DASHBOARD_UID)
                .description("Сгенерировано автоматически по /actuator/measured. Правки будут затёрты.")
                .tags(List.of("ddia", "generated"))
                .readonly()
                .refresh("10s")
                .time(new DashboardDashboardTimeBuilder().from("now-15m").to("now"))
                .withVariable(instanceVariable("datacenter", "Датацентр", datasource,
                        PromQl.labelValues(throughput, "datacenter")))
                .withVariable(instanceVariable("pod", "Под", datasource,
                        // the pod list is narrowed by the selected datacenter
                        PromQl.labelValuesFilteredByDatacenter(throughput, "pod")));

        dashboard.withRow(new RowBuilder("Итого по всем ручкам"))
                .withPanel(totalThroughputPanel(datasource, throughput))
                .withPanel(totalErrorsPanel(datasource, throughput));

        for (MeasuredHandlers.Handler handler : discovered.handlers()) {
            for (String method : handler.methods()) {
                String route = handler.route();
                dashboard.withRow(new RowBuilder(method + " " + route))
                        .withPanel(latencyPanel(datasource, latency, route, method))
                        .withPanel(throughputPanel(datasource, throughput, route, method))
                        .withPanel(errorsPanel(datasource, throughput, route, method));
            }
        }

        return dashboard;
    }

    private static QueryVariableBuilder instanceVariable(String name, String label, DataSourceRef datasource, String query) {
        return new QueryVariableBuilder(name)
                .label(label)
                .datasource(datasource)
                .query(StringOrMap.createString(query))
                .multi(true)
                .includeAll(true)
                .allValue(".*")
                .refresh(VariableRefresh.ON_TIME_RANGE_CHANGED)
                .sort(VariableSort.ALPHABETICAL_ASC);
    }

    private static TimeseriesPanelBuilder latencyPanel(DataSourceRef datasource, String latency,
                                                       String route, String method) {
        TimeseriesPanelBuilder panel = new TimeseriesPanelBuilder()
                .title("Latency, перцентили")
                .description("histogram_quantile поверх суммы бакетов — корректно при выборе нескольких подов")
                .datasource(datasource)
                .unit("s")
                .min(0.0)
                .span(8)
                .height(8);
        for (String quantile : PromQl.PERCENTILES) {
            panel.withTarget(new DataqueryBuilder()
                    .expr(PromQl.latencyPercentile(latency, route, method, quantile))
                    .legendFormat("p" + quantile.substring(2))
                    .range());
        }
        return panel;
    }

    private static TimeseriesPanelBuilder throughputPanel(DataSourceRef datasource, String throughput,
                                                          String route, String method) {
        return new TimeseriesPanelBuilder()
                .title("Throughput, rps")
                .datasource(datasource)
                .unit("reqps")
                .min(0.0)
                .span(8)
                .height(8)
                .withTarget(new DataqueryBuilder()
                        .expr(PromQl.throughput(throughput, route, method))
                        .legendFormat("rps")
                        .range());
    }

    private static TimeseriesPanelBuilder errorsPanel(DataSourceRef datasource, String throughput,
                                                      String route, String method) {
        return new TimeseriesPanelBuilder()
                .title("Errors rate по кодам")
                .datasource(datasource)
                .unit("reqps")
                .min(0.0)
                .span(8)
                .height(8)
                .withTarget(new DataqueryBuilder()
                        .expr(PromQl.errorsByStatus(throughput, route, method))
                        .legendFormat("{{status}}")
                        .range());
    }

    private static TimeseriesPanelBuilder totalThroughputPanel(DataSourceRef datasource, String throughput) {
        return new TimeseriesPanelBuilder()
                .title("Throughput по ручкам, rps")
                .datasource(datasource)
                .unit("reqps")
                .min(0.0)
                .span(12)
                .height(8)
                .withTarget(new DataqueryBuilder()
                        .expr(PromQl.throughputByHandler(throughput))
                        .legendFormat("{{method}} {{route}}")
                        .range());
    }

    private static TimeseriesPanelBuilder totalErrorsPanel(DataSourceRef datasource, String throughput) {
        return new TimeseriesPanelBuilder()
                .title("Errors rate по кодам, rps")
                .datasource(datasource)
                .unit("reqps")
                .min(0.0)
                .span(12)
                .height(8)
                .withTarget(new DataqueryBuilder()
                        .expr(PromQl.errorsByStatusTotal(throughput))
                        .legendFormat("{{status}}")
                        .range());
    }
}